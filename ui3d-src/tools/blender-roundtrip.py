"""Run: blender --background --python tools/blender-roundtrip.py -- output-folder"""
import bpy
import importlib.util
import json
import math
import pathlib
import sys
from mathutils import Matrix

root = pathlib.Path(__file__).resolve().parents[1]
output = pathlib.Path(sys.argv[sys.argv.index('--') + 1]) if '--' in sys.argv else root / 'tools' / 'roundtrip-output'
output.mkdir(parents=True, exist_ok=True)
spec = importlib.util.spec_from_file_location('sample_device', root / 'blender-addon' / 'sample_device.py')
sample = importlib.util.module_from_spec(spec)
spec.loader.exec_module(sample)
scene = sample.build_scene()
bpy.context.view_layer.update()

# The standard exporter converts each node's coordinates by this basis.
basis = Matrix.Rotation(-math.pi / 2, 4, 'X')
objects = []
for obj in scene.objects:
    world = basis @ obj.matrix_world @ basis.inverted()
    position, rotation, scale = world.decompose()
    if obj.type == 'CAMERA':
        # glTF cameras already use Blender's local -Z viewing axis; only the world basis changes.
        position, rotation, scale = (basis @ obj.matrix_world).decompose()
    item = {'name': obj.name, 'type': obj.type, 'position': list(position),
            'quaternion': [rotation.x, rotation.y, rotation.z, rotation.w], 'scale': list(scale)}
    if obj.type == 'MESH' and (obj.name.startswith('canvas_') or obj.name == 'broadcastCanvas'):
        item['uvs'] = sorted({(round(uv.uv.x, 6), round(1.0 - uv.uv.y, 6)) for uv in obj.data.uv_layers.active.data})
    objects.append(item)

report = {'blenderVersion': bpy.app.version_string, 'objects': objects,
          'clips': ['POWER_ON_anim', 'POWER_OFF_anim', 'BROADCAST_ACTIVE_LOOP_anim'],
          'blenderZInGltf': [0, 1, 0]}
(output / 'expected.json').write_text(json.dumps(report, indent=4), encoding='utf-8')
definition = json.loads((root / 'public' / 'devices' / 'classic-demo' / 'device.json').read_text(encoding='utf-8'))
definition['model'] = 'device.glb'
(output / 'device.json').write_text(json.dumps(definition, indent=4), encoding='utf-8')
bpy.ops.export_scene.gltf(filepath=str(output / 'device.glb'), export_format='GLB', export_extras=True,
                          export_yup=True, export_cameras=True, export_animations=True, export_animation_mode='NLA_TRACKS')
print('UI3D round-trip fixture generated by Blender', bpy.app.version_string)
